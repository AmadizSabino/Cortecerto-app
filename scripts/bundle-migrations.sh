#!/bin/bash
# Writes supabase/pending/0003_to_LAST.sql: migrations 0003 onwards in one file,
# for a project that has already run 0001 and 0002. Paste it once in the
# Supabase SQL editor. It runs as one transaction: all of it, or none.
# CI checks that the file is up to date and that it applies cleanly.
set -euo pipefail
cd "$(dirname "$0")/.."
files=$(ls supabase/migrations/*.sql | sort | awk -F/ '$NF >= "0003"')
last=$(basename "$(echo "$files" | tail -1)" | cut -c1-4)
out="supabase/pending/0003_to_${last}.sql"
mkdir -p supabase/pending
rm -f supabase/pending/*.sql
{
  echo "-- CorteCerto: migrations 0003 to ${last} in one go, for a project that has run 0001 and 0002."
  echo "-- Generated by scripts/bundle-migrations.sh from supabase/migrations/. Do not edit by hand."
  echo "-- Paste all of it in Supabase > SQL Editor and press Run. If anything fails, nothing is applied."
  echo "begin;"
  for f in $files; do
    echo
    echo "-- ======================================================================"
    echo "-- $(basename "$f")"
    echo "-- ======================================================================"
    cat "$f"
  done
  echo
  echo "commit;"
} > "$out"
echo "$out"
